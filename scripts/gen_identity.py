"""Generate src/pdo/identity_slots.py from the schema's hashable/unhashable slot markers.

Every slot of every class must carry exactly one marker (DAPPER-ID-1 style); an unmarked or doubly
marked slot is an error, so a new slot can never silently enter or escape a content digest.

    uv run python scripts/gen_identity.py            # write src/pdo/identity_slots.py
    uv run python scripts/gen_identity.py --check    # lint only
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from linkml_runtime.utils.schemaview import SchemaView

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schema" / "pdo.yaml"
OUT = ROOT / "src" / "pdo" / "identity_slots.py"
MARKERS = {"hashable", "unhashable"}


def identity_table(sv: SchemaView) -> tuple[dict[str, tuple[str, ...]], list[str]]:
    table: dict[str, tuple[str, ...]] = {}
    problems: list[str] = []
    for cls in sorted(sv.all_classes()):
        if cls == "Any" or sv.get_class(cls).mixin:
            continue
        id_slot = sv.get_identifier_slot(cls)
        id_name = id_slot.name if id_slot is not None else None
        hashable = []
        for slot in sv.class_induced_slots(cls):
            if slot.name == id_name or slot.name in MARKERS:
                continue
            marks = MARKERS & set(slot.mixins or [])
            if len(marks) != 1:
                problems.append(f"{cls}.{slot.name}: needs exactly one of hashable/unhashable, has {sorted(marks)}")
            elif "hashable" in marks:
                hashable.append(slot.name)
        table[cls] = tuple(sorted(hashable))
    return table, problems


def render(table: dict[str, tuple[str, ...]]) -> str:
    lines = [
        '"""Hashable slots per class, generated by scripts/gen_identity.py from schema/*.yaml. Do not edit."""',
        "",
        "HASHABLE: dict[str, tuple[str, ...]] = {",
    ]
    for cls, slots in table.items():
        lines.append(f"    {cls!r}: {slots!r},")
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="lint the markers without writing")
    args = parser.parse_args()
    table, problems = identity_table(SchemaView(str(SCHEMA)))
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    if not args.check:
        OUT.write_text(render(table))
        print(f"wrote {OUT.relative_to(ROOT)} ({len(table)} classes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
